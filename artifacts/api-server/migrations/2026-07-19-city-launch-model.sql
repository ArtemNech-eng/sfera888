-- Migration: City Launch Model — разграничение «запущенных» и «пре-лонч» городов
-- Spec: .kiro/specs/city-launch-model/
--
-- Аддитивная миграция: добавляет колонку `is_launched` в существующую таблицу
-- `cities` и помечает Краснодар как запущенный город. НЕ изменяет и НЕ удаляет
-- существующие столбцы/строки, поэтому текущий CRM/PWA/маркетплейс продолжают
-- работать без изменений.
--
-- Семантика флага:
--   is_launched=true                       — город операционно запущен: есть
--                                            мастера, полный опыт маркетплейса
--                                            (каталог, обычная форма заявки,
--                                            длинный хвост «услуга×город»).
--   is_geo_covered=true, is_launched=false — «пре-лонч/SEO»: хаб-/контентные
--                                            страницы индексируются и копят вес,
--                                            но каталог/приём заявок не открыты.
--
-- Идемпотентность: ADD COLUMN IF NOT EXISTS + UPDATE по slug — повторный прогон
-- безопасен для running production. Зеркалит runtime-fix в
-- artifacts/api-server/src/index.ts (runRuntimeFixes).

-- =============================================================================
-- 1. ALTER TABLE cities — операционный запуск города (is_launched)
-- =============================================================================

ALTER TABLE cities
  ADD COLUMN IF NOT EXISTS is_launched boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN cities.is_launched IS 'Город операционно запущен (есть мастера, полный опыт маркетплейса). false + is_geo_covered=true = пре-лонч/SEO (spec: city-launch-model)';

-- =============================================================================
-- 2. Запуск флагманского города — Краснодар
-- =============================================================================
-- Безусловно (idempotent), чтобы флагманский город никогда случайно не
-- «схлопнулся» в 404 из-за дефолта false. Остальные города переключаются по
-- факту масштабирования (UPDATE cities SET is_launched = true WHERE slug = '...').

UPDATE cities SET is_launched = true WHERE slug = 'krasnodar';
